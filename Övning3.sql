4. Vad är SQL Server Replication?
SQL Server Replication är en teknik som automatiskt kopierar och synkroniserar data mellan databaser så att flera system alltid har exakt samma information

5. Vad är Mirroring i SQL Server?
Database Mirroring skapar en exakt reservkopia av en databas på en annan server för att snabbt kunna ta över vid en krasch och minimera driftstopp

6. Vad är AlwaysOn Availability Groups i SQL Server?
Always On Availability Groups synkroniserar grupper av databaser till upp till åtta reservservrar och flyttar automatiskt över trafiken på några sekunder vid ett serverhaveri